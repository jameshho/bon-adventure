#!/usr/bin/env python3
"""NPC list for docs/guides/NPCS.md, generated from the registry (data/npcs.json).

Rewrites the part of the guide between the markers
  <!-- npc-report:start --> and <!-- npc-report:end -->
with the count by building and one table row per NPC. Run from BonAdventure/ after changing
the registry:

  python3 tools/npc_report.py --write     # update the guide
  python3 tools/npc_report.py             # print the generated part; exit 1 if the guide is stale

Names come from data/phrases.json (name_phrase, English) or the entry's name; roles from the
registry; nothing is hand-written in the guide's table.
"""
from __future__ import annotations

import json
import sys
from collections import Counter
from pathlib import Path

PROJECT = Path(__file__).resolve().parent.parent
GUIDE = PROJECT / "docs" / "guides" / "NPCS.md"
START = "<!-- npc-report:start -->"
END = "<!-- npc-report:end -->"


def load(name: str) -> dict:
    return json.loads((PROJECT / "data" / name).read_text(encoding="utf-8"))


def report() -> str:
    data = load("npcs.json")
    units = load("buildings.json")["units"]
    phrases = load("phrases.json")["phrases"]
    npcs = data["npcs"]

    def phrase(pid: str) -> str:
        group, _, key = pid.partition(".")
        return phrases.get(group, {}).get(key, {}).get("en", pid)

    def label(unit: str) -> str:
        return units.get(unit, {}).get("label", unit) if unit else "Not placed (cast only)"

    def where(n: dict) -> str:
        p = n.get("placement", "")
        if p == "house":
            return "Home seat" + ("" if n.get("in_house", True) else " (kept, not in the house)")
        if p == "cast":
            return "Avatar, stand-in, random customer"
        if p == "runtime":
            return "Made by `%s`" % n.get("owner", "").split("/")[-1] + (" (%s)" % n["seat"].split(" (")[0] if n.get("seat") else "")
        return "`%s`" % n.get("node", "")

    def coord(n: dict) -> str:
        at = n.get("at")
        return "(%g, %g, %g)" % tuple(at) if at else "—"

    in_town = [n for n in npcs if n.get("placement") != "cast" and n.get("in_house", True)]
    by_unit = Counter(n.get("unit", "") for n in in_town)
    roles = Counter(n.get("role", "") for n in in_town)
    lines = [START, "",
             "Generated by `python3 tools/npc_report.py --write` from `data/npcs.json`; do not edit by hand.", "",
             "**%d NPCs in the town** (%d with an activity, %d without), plus %d cast members who appear only as "
             "profile avatars, tutorial stand-ins and random customers. Not counted: the player, zoo and farm "
             "animals, and game pieces made during a minigame (lineup suspects, bank customers, restaurant "
             "guests, the warehouse game's copy of Ramón, the tutorial's cast)." % (
                 len(in_town), roles.get("host", 0), len(in_town) - roles.get("host", 0),
                 len([n for n in npcs if n.get("placement") == "cast" or not n.get("in_house", True)])), "",
             "| Building (unit) | NPCs |", "| --- | --- |"]
    for unit in sorted(by_unit, key=lambda u: (-by_unit[u], label(u))):
        lines.append("| %s (`%s`) | %d |" % (label(unit), unit, by_unit[unit]))
    lines += ["", "| id | Name | Plush | Costume | Unit | Placed | Town position (at) | Pose | Role | Chatter |",
              "| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |"]
    for n in sorted(npcs, key=lambda n: (n.get("unit", "~"), n["id"])):
        name = phrase(n["name_phrase"]) if n.get("name_phrase") else n.get("name", "")
        if not name:
            name = "(%s)" % n.get("word", "")
        role = n.get("role", "")
        if n.get("activity"):
            role += ": `%s`" % n["activity"]
        costume = n.get("work_costume") or n.get("costume") or ""
        lines.append("| `%s` | %s | %s | %s | %s | %s | %s | %s | %s | %s |" % (
            n["id"], name, n.get("species", ""), costume, n.get("unit", "—"), where(n), coord(n),
            n.get("pose", "—"), role, n.get("chatter", "")))
    lines += ["", END]
    return "\n".join(lines)


def main() -> int:
    text = report()
    guide = GUIDE.read_text(encoding="utf-8")
    start, end = guide.find(START), guide.find(END)
    if start < 0 or end < 0:
        print("markers missing in", GUIDE)
        return 1
    updated = guide[:start] + text + guide[end + len(END):]
    if "--write" in sys.argv:
        GUIDE.write_text(updated, encoding="utf-8")
        print("wrote", GUIDE.relative_to(PROJECT))
        return 0
    print(text)
    return 0 if updated == guide else 1


if __name__ == "__main__":
    sys.exit(main())
